-- Strip all color from nvim-web-devicons: patch get_icon to return white highlight
local gothic_group = vim.api.nvim_create_augroup("GothicIconFix", { clear = true })
local function patch_devicons()
  local ok, devicons = pcall(require, "nvim-web-devicons")
  if ok then
    local original_get_icon = devicons.get_icon
    devicons.get_icon = function(name, ext, opts)
      local icon, _ = original_get_icon(name, ext, opts)
      return icon or "?", "NeoTreeFileIcon"
    end
  end
  return ok
end

-- Try immediately, then on VeryLazy, then as fallback on each neo-tree buffer
if not patch_devicons() then
  vim.api.nvim_create_autocmd("User", {
    group = gothic_group, pattern = "VeryLazy",
    callback = patch_devicons,
  })
end
vim.api.nvim_create_autocmd("FileType", {
  group = gothic_group, pattern = "neo-tree",
  callback = function()
    patch_devicons()
    vim.api.nvim_set_hl(0, "NeoTreeDirectoryIcon", { fg = "#ffffff" })
    vim.api.nvim_set_hl(0, "NeoTreeFileIcon", { fg = "#ffffff" })
    vim.api.nvim_set_hl(0, "NeoTreeExpander", { fg = "#666666" })
    vim.api.nvim_set_hl(0, "NeoTreeIndentMarker", { fg = "#222222" })
  end,
})

